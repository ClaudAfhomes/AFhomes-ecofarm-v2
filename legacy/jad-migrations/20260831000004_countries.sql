-- Countries master data - ISO 3166-1 alpha-2 canonical reference
-- E-31 Country (config). Reference for location verification, member profile, public config.
-- No bounding boxes / polygons / coordinate logic - provider resolves country, this table validates/identifies.
-- Follows existing RLS pattern (cms_contents): public read (anon, authenticated), service_role write.

create table if not exists public.countries (
  code char(2) primary key check (code ~ '^[A-Z]{2}$'),
  name text not null,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Keep updated_at in sync
create or replace function public.countries_set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists countries_updated_at on public.countries;
create trigger countries_updated_at
  before update on public.countries
  for each row execute function public.countries_set_updated_at();

-- RLS
alter table public.countries enable row level security;
do $$ begin
  if not exists (select 1 from pg_policies where tablename='countries' and policyname='countries_read_all') then
    create policy countries_read_all on public.countries for select to anon, authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies where tablename='countries' and policyname='countries_service_all') then
    create policy countries_service_all on public.countries for all to service_role using (true) with check (true);
  end if;
end $$;

-- Indexes
create index if not exists countries_is_active_idx on public.countries (is_active) where is_active = true;

